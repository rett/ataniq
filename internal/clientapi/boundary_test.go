package clientapi

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// TestImportsNoOtherPackageOfTheRepository keeps the wire structs this
// package's own: it must not import anything else from this module.
func TestImportsNoOtherPackageOfTheRepository(t *testing.T) {
	files, err := filepath.Glob("*.go")
	if err != nil || len(files) == 0 {
		t.Fatalf("no files: %v", err)
	}
	fset := token.NewFileSet()
	for _, name := range files {
		src, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		f, err := parser.ParseFile(fset, name, src, parser.ImportsOnly)
		if err != nil {
			t.Fatal(err)
		}
		for _, imp := range f.Imports {
			path, _ := strconv.Unquote(imp.Path.Value)
			if path == "ataniq" || strings.HasPrefix(path, "ataniq/") {
				t.Errorf("%s imports %s", name, path)
			}
		}
	}
}
