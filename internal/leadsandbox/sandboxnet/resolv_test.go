func addrs(t *testing.T, ss ...string) []netip.Addr {
	t.Helper()
	var out []netip.Addr
	for _, s := range ss {
		out = append(out, netip.MustParseAddr(s))
	}
	return out
}

func refusalReason(t *testing.T, err error) string {
	t.Helper()
	if !errors.Is(err, ErrRefused) {
		t.Fatalf("error %v is not a refusal", err)
	}
	var r *Refusal
	if !errors.As(err, &r) || r.Reason == "" {
		t.Fatalf("error %v carries no reason", err)
	}
	return r.Reason
}

func mustContain(t *testing.T, got string, parts ...string) {
	t.Helper()
	for _, p := range parts {
		if !strings.Contains(got, p) {
			t.Errorf("%q does not contain %q", got, p)
		}
	}
}

func notesContain(t *testing.T, res Result, part string) {
	t.Helper()
	for _, n := range res.Notes {
		if strings.Contains(n, part) {
			return
		}
	}
	t.Errorf("no note contains %q: %q", part, res.Notes)
}

const stubFile = "# stub\nnameserver 127.0.0.53\noptions edns0 trust-ad\nsearch lan\n"
const upstreamFile = "# upstream\nnameserver 192.0.2.1\nnameserver 2001:db8::53\nsearch example.test\n"

func TestStubWithUpstream(t *testing.T) {
	for _, tc := range []struct {
		name string
		in   Input
	}{
		{"by real path", Input{HostContent: []byte(stubFile), HostRealPath: SystemdStubPath}},
		{"by only nameserver", Input{HostContent: []byte(stubFile), HostRealPath: "/etc/resolv.conf"}},
		{"real path alone, content unreadable as stub", Input{HostContent: []byte("garbage \x00"), HostRealPath: SystemdStubPath}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			tc.in.UpstreamPresent = true
			tc.in.UpstreamContent = []byte(upstreamFile)
			res, err := Derive(tc.in)
			if err != nil {
				t.Fatal(err)
			}
			if res.Source != SourceSystemdUpstream {
				t.Errorf("source %q", res.Source)
			}
			want := "# Generated by ataniq for the lead sandbox from the systemd-resolved upstream file.\n" +
				"nameserver 192.0.2.1\nnameserver 2001:db8::53\nsearch example.test\n"
			if string(res.Content) != want {
				t.Errorf("content\n%s\nwant\n%s", res.Content, want)
			}
			notesContain(t, res, "stub")
		})
	}
}

